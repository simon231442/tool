#include <unistd.h>

int	main(int ac, char **av)
{
	int		i;
	int 	m;
	(void)ac;

	i = 0;
	while (av[1][i])
	{
		if (av[1][i] == ' ')
			write(1, " " , 1);
		else
		{
			m = 0;
			while (m++ <= i)
				write (1, &av[1][i], 1);
		}
		i++;
	}
	return (0);
}


